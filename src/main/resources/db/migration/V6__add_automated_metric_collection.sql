-- Automated KPI actuals.
--
-- Adds the two tables that make measurement executable, and somewhere on `kpis`
-- to hold an observation without it becoming the record.

-- ---------------------------------------------------------------------------
-- Who someone is in an external system
-- ---------------------------------------------------------------------------
-- A GitHub login rarely matches a corporate email, so a metric cannot be
-- attributed without an explicit mapping. Its own table rather than a column on
-- `users`, so a second provider needs no schema change.
CREATE TABLE public.user_external_identities (
    id              bigint      NOT NULL,
    user_id         bigint      NOT NULL,
    provider_code   varchar(50) NOT NULL,
    external_handle varchar(255) NOT NULL,
    active          boolean     NOT NULL DEFAULT true,
    created_at      timestamp(6) NOT NULL,
    updated_at      timestamp(6) NOT NULL
);

ALTER TABLE public.user_external_identities
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.user_external_identities_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.user_external_identities
    ADD CONSTRAINT user_external_identities_pkey PRIMARY KEY (id);

-- Two handles for one person on one provider would make the collected number
-- depend on row order.
ALTER TABLE ONLY public.user_external_identities
    ADD CONSTRAINT uk_user_external_identity UNIQUE (user_id, provider_code);

ALTER TABLE ONLY public.user_external_identities
    ADD CONSTRAINT fk_user_external_identity_user
        FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

-- ---------------------------------------------------------------------------
-- How a KPI is measured
-- ---------------------------------------------------------------------------
-- kpi_masters.data_source is free text describing intent to a human. This is
-- the executable form: provider, metric, and any scope it needs.
CREATE TABLE public.kpi_metric_bindings (
    id            bigint       NOT NULL,
    kpi_master_id bigint       NOT NULL,
    provider_code varchar(50)  NOT NULL,
    metric_key    varchar(100) NOT NULL,
    config_json   text,
    active        boolean      NOT NULL DEFAULT true,
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6) NOT NULL
);

ALTER TABLE public.kpi_metric_bindings
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.kpi_metric_bindings_id_seq
        START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
    );

ALTER TABLE ONLY public.kpi_metric_bindings
    ADD CONSTRAINT kpi_metric_bindings_pkey PRIMARY KEY (id);

-- Two bindings on one KPI would produce two competing actuals with no rule for
-- choosing between them.
ALTER TABLE ONLY public.kpi_metric_bindings
    ADD CONSTRAINT uk_kpi_metric_binding_master UNIQUE (kpi_master_id);

ALTER TABLE ONLY public.kpi_metric_bindings
    ADD CONSTRAINT fk_kpi_metric_binding_master
        FOREIGN KEY (kpi_master_id) REFERENCES public.kpi_masters(id) ON DELETE CASCADE;

-- ---------------------------------------------------------------------------
-- Observed values on the KPI instance
-- ---------------------------------------------------------------------------
-- Deliberately separate from actual_value: the employee accepts a suggestion,
-- the system never writes one on their behalf.
ALTER TABLE public.kpis ADD COLUMN suggested_actual_value   double precision;
ALTER TABLE public.kpis ADD COLUMN suggested_actual_source  varchar(50);
ALTER TABLE public.kpis ADD COLUMN suggested_actual_summary text;
ALTER TABLE public.kpis ADD COLUMN suggested_actual_url     text;
ALTER TABLE public.kpis ADD COLUMN suggested_actual_at      timestamp(6);

-- Lookup is always "the binding for this KPI master" and "this user's handle
-- for this provider"; both are covered by the unique constraints above.
CREATE INDEX idx_user_external_identities_provider
    ON public.user_external_identities (provider_code);

